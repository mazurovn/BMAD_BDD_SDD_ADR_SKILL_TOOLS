#!/usr/bin/env python3
"""Rewrite skills, agents, and the thin wiki into operating procedures."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def bullets(items: list[str]) -> str:
    return "\n".join(f"- {item}" for item in items)


def numbered(items: list[str]) -> str:
    return "\n".join(f"{i}. {item}" for i, item in enumerate(items, 1))


def skill(data: dict) -> str:
    return f"""---
name: {data["name"]}
description: {data["description"]}
---

# {data["title"]}

{data["purpose"]}

## Ответственность

Владелец: {data["owner"]}.
Код, который проверяет результат: `{data["code"]}`.
Если вопрос принадлежит другой роли, этот скилл останавливается и называет её. Он не закрывает чужой гейт и не подменяет чужое решение.

## Когда открывать

{bullets(data["when"])}

## Когда не открывать

{bullets(data["when_not"])}

## Входы, без которых процедуру не начинают

{bullets(data["inputs"])}

## Процедура

{numbered(data["steps"])}

## Гейты и гардрейлы

{bullets(data["gates"])}

Ненулевой код выхода — это отказ. Агент не пишет, что шаг пройден, пока в stdout нет `PASS`.

## Делать

{bullets(data["do"])}

## Не делать

{bullets(data["dont"])}

## Контроль качества

{bullets(data["qc"])}

## Как выглядит провал

{bullets(data["fail"])}

## Передача

{data["handoff"]}

## Пример команд

```bash
{data["example"]}
```

## Применение инструментов

Каждая команда выше — это `python3 cli/mazu.py ...` из корня набора. Схему вызова для модели берут из `tools/openai.json` или `tools/gigachat.json` и не выдумывают имя функции. Результат известен только после stdout.
"""


def agent(data: dict) -> str:
    stats = "\n".join(f"- {name}: {score}" for name, score in data["stats"])
    return f"""# {data["title"]}

## Задача

{data["mission"]}

## Модель мышления

{data["model"]}

## Статы

{stats}

5 означает, что роль это оптимизирует. 0 означает, что оптимизировать это ей запрещено. Это приоритеты, не замер скорости.

## Ответственность

{data["responsibility"]}

Слепое пятно: {data["blind"]}.
Когда роль в него упирается, она называет соседнюю роль и останавливается.

## Гейт, который роль держит

{bullets(data["gates"])}

## Процедура одной сессии

{numbered(data["steps"])}

## Инструменты и как их применять

{bullets(data["tools"])}

Пока команда не вернула stdout, роль не описывает результат. `tools` печатает владельца команды. `guide {data["guide"]}` печатает связанный раздел руководства.

## Делать

{bullets(data["do"])}

## Не делать

{bullets(data["dont"])}

## Гардрейлы

{bullets(data["guards"])}

## Контроль качества перед ответом человеку

{bullets(data["qc"])}

## Передача

{data["handoff"]}

## Код

{data["code"]}
"""


